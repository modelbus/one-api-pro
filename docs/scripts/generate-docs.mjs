// Generate
// ---------------------------------------------------------------------------
let created = 0
let skipped = 0

for (const [dir, slug, titleZh, titleEn, order, descZh, descEn] of CATALOG) {
  for (const [lang, title, desc] of [
    ['zh', titleZh, descZh],
    ['en', titleEn, descEn],
  ]) {
    const filePath = join(DOCS, dir, `${slug}-${lang}.md`)
    if (existsSync(filePath)) {
      skipped++
      continue
    }
    const fm = [
      '---',
      `title: ${title}`,
      `description: ${desc}`,
      `category: ${dir}`,
      `order: ${order}`,
      '---',
      '',
      `# ${title}`,
      '',
      `> ${desc}`,
      '',
      '## 概述 / Overview',
      '',
      lang === 'zh'
        ? '本页内容正在编写中。详细说明请参考英文版本或提交 PR。'
        : 'This page is being written. Refer to the Chinese version or open a PR.',
      '',
    ].join('\n')
    writeFileSync(filePath, fm, 'utf8')
    created++
  }
}

console.log(`created=${created} skipped=${skipped}`)
